const pathToTab: Record<string, string> = {
  '/': 'dashboard',
  '/wallet': 'wallet',
  '/market': 'market',
  '/transactions': 'transactions',
  '/settings': 'settings',
};

export function AppLayout() {
  const [activeTab, setActiveTab] = useState('dashboard');
  const location = useLocation();

  useEffect(() => {
    const currentTab = pathToTab[location.pathname] || 'dashboard';
    setActiveTab(currentTab);
  }, [location.pathname]);

  const handleTabChange = (tabId: string) => {
    setActiveTab(tabId);
    const paths: Record<string, string> = {
      dashboard: '/',
      wallet: '/wallet',
      market: '/market',
      transactions: '/transactions',
      settings: '/settings',
    };
    if (paths[tabId]) {
      window.history.pushState({}, '', paths[tabId]);
      window.dispatchEvent(new PopStateEvent('popstate'));
    }
  };

  return (
    <div className="min-h-screen bg-safepal-dark-50 flex flex-col">
      <Outlet />
      <BottomNav items={navItems} activeItem={activeTab} onChange={handleTabChange} />
    </div>
  );
}